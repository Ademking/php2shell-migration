#!/usr/bin/env python3
"""Refresh references/frameworks/framework-lifecycle.json from the endoflife.date API.

This is the ONLY script in the skill that uses the network, and only when run explicitly.
endoflife.date is a trusted secondary source: confirm critical decisions against the
official project page linked from each framework reference.

Usage: refresh-lifecycle-data.py [--output PATH]
"""
import argparse
import datetime
import json
import os
import sys
import urllib.error
import urllib.request

# framework id used by detect-project.py -> endoflife.date product slug
PRODUCTS = {
    "php": "php", "laravel": "laravel", "symfony": "symfony", "wordpress": "wordpress", "drupal": "drupal",
    "codeigniter": "codeigniter", "yii": "yii", "cakephp": "cakephp", "joomla": "joomla",
    "october-cms": "octobercms", "suitecrm": "suitecrm", "espocrm": "espocrm", "nextcloud": "nextcloud",
    "magento": "magento", "prestashop": "prestashop", "opencart": "opencart", "slim": "slim",
    "dolibarr": "dolibarr", "typo3": "typo3", "moodle": "moodle", "mediawiki": "mediawiki",
    "laminas": "laminas", "phalcon": "phalcon", "phpmyadmin": "phpmyadmin",
}
API = "https://endoflife.date/api/v1/products/{}"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "references", "frameworks", "framework-lifecycle.json")


def fetch(slug):
    req = urllib.request.Request(API.format(slug), headers={"User-Agent": "php2shell-migration-skill"})
    with urllib.request.urlopen(req, timeout=20) as resp:
        return json.load(resp)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--output", default=OUT)
    a = ap.parse_args(argv)
    data = {"_comment": "Generated by scripts/refresh-lifecycle-data.py. Secondary source; verify against official links.",
            "verified_on": datetime.date.today().isoformat(), "source": "https://endoflife.date/", "products": {}, "unavailable": {}}
    for fid, slug in PRODUCTS.items():
        try:
            releases = fetch(slug)["result"]["releases"]
        except (urllib.error.URLError, OSError, KeyError, ValueError) as exc:
            data["unavailable"][fid] = f"{slug}: {exc}"
            continue
        data["products"][fid] = {"source": f"https://endoflife.date/{slug}", "releases": [
            {"cycle": r["name"], "release_date": r.get("releaseDate"), "eol": r.get("eolFrom") or r.get("isEol"),
             "is_eol": bool(r.get("isEol")), "latest": (r.get("latest") or {}).get("name"),
             "supported_php": (r.get("custom") or {}).get("supportedPhpVersions")}
            for r in releases]}
    with open(a.output, "w", encoding="utf-8") as fh:
        json.dump(data, fh, indent=1)
        fh.write("\n")
    print(f"wrote {a.output}: {len(data['products'])} products, unavailable: {sorted(data['unavailable'])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
